#perform the following operations on the given two sets:
#-union
#-intersection
#-difference
#set_a={1,2,3,4}
#set_b={3,4,5,6}

#union
set_a={1,2,3,4}
set_b={3,4,5,6}

print("union:",set_a.union(set_b))

#Intersection
set_a={1,2,3,4}
set_b={3,4,5,6}

print("Intersection:",set_a.intersection(set_b))

#difference
set_a={1,2,3,4}
set_b={3,4,5,6}

print("difference:",set_a.difference(set_b))
print("difference:",set_b.difference(set_a))